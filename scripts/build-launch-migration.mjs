// Builds migrations/0005_launch_content.sql from a LOCAL database that holds only the real launch
// content (Charlie's results, articles and link cards; no fictional samples, no example ads).
//
//   node scripts/build-launch-migration.mjs --persist-to <dir of that local database>
//
// Every row is linked by its natural identity (a sire by name, a horse by name + year + sire + dam,
// an event by name + start date + country) instead of internal ids, and every insert is
// INSERT OR IGNORE / WHERE NOT EXISTS, so the migration is safe to run on a database that already
// has some of this content and adds nothing when run twice.
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const args = process.argv.slice(2);
const persist = args[args.indexOf('--persist-to') + 1];
if (!args.includes('--persist-to') || !persist) { console.error('Usage: node scripts/build-launch-migration.mjs --persist-to <dir>'); process.exit(1); }

function rows(sql) {
  const r = spawnSync('npx', ['wrangler', 'd1', 'execute', 'irishbredeventers', '--local', '--persist-to', persist, '--json', '--command', sql], { encoding: 'utf8', maxBuffer: 1 << 28 });
  if (r.status !== 0) throw new Error(r.stderr || r.stdout);
  return JSON.parse(r.stdout.slice(r.stdout.indexOf('[')))[0].results;
}

// Line breaks inside text values are held as NL until add() has tidied the SQL layout, so paragraphs survive.
const NL = '\u0001';
const q = v => v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''").replace(/\n/g, NL)}'`;
const sireId = n => n ? `(SELECT id FROM sires WHERE name_normalised = ${q(n)})` : 'NULL';
const damId = (n, sireN) => n ? `(SELECT id FROM dams WHERE name_normalised = ${q(n)} AND sire_key = IFNULL(${sireId(sireN)}, 0))` : 'NULL';
const breederId = (n, county) => n ? `(SELECT id FROM breeders WHERE name_normalised = ${q(n)} AND county = ${q(county || '')})` : 'NULL';
const horseId = h => `(SELECT id FROM horses WHERE name_normalised = ${q(h.h_norm)} AND IFNULL(birth_year, 0) = ${Number(h.h_year) || 0}
    AND IFNULL(sire_id, 0) = IFNULL(${sireId(h.h_sire)}, 0) AND IFNULL(dam_id, 0) = IFNULL(${damId(h.h_dam, h.h_dam_sire)}, 0))`;
const eventId = e => `(SELECT id FROM events WHERE name = ${q(e.ev_name)} AND start_date = ${q(e.ev_start)} AND country = ${q(e.ev_country)})`;
const classId = e => `(SELECT id FROM classes WHERE event_id = ${eventId(e)} AND name = ${q(e.cl_name)})`;
const batchId = label => label ? `(SELECT id FROM batches WHERE label = ${q(label)} ORDER BY id LIMIT 1)` : 'NULL';

// Columns that identify a horse (joined into several queries below)
const HORSE_KEY = `h.name_normalised AS h_norm, h.birth_year AS h_year, hs.name_normalised AS h_sire, hd.name_normalised AS h_dam, hds.name_normalised AS h_dam_sire`;
const HORSE_JOIN = `LEFT JOIN sires hs ON hs.id = h.sire_id LEFT JOIN dams hd ON hd.id = h.dam_id LEFT JOIN sires hds ON hds.id = hd.sire_id`;
const EVENT_KEY = `e.name AS ev_name, e.start_date AS ev_start, e.country AS ev_country`;

const out = [
  '-- Launch content: Charlie Ripman\'s results (week of 6 April 2026 and 14-16 February 2025), his articles',
  '-- and the external link cards, as they are in the approved preview. No fictional sample results and',
  '-- no example ads. Generated by scripts/build-launch-migration.mjs; do not edit by hand.',
  '-- Safe to run more than once: rows are matched on their natural identity and never duplicated.',
  ''
];
const add = s => out.push(s.replace(/\n\s+/g, ' ').split(NL).join('\n') + ';');

// Breeding records
for (const s of rows('SELECT name, name_normalised, breed_code, tih_flag FROM sires ORDER BY id')) {
  add(`INSERT OR IGNORE INTO sires (name, name_normalised, breed_code, tih_flag) VALUES (${q(s.name)}, ${q(s.name_normalised)}, ${q(s.breed_code)}, ${s.tih_flag})`);
}
for (const d of rows('SELECT d.name, d.name_normalised, d.breed_code, d.tih_flag, s.name_normalised AS sire FROM dams d LEFT JOIN sires s ON s.id = d.sire_id ORDER BY d.id')) {
  add(`INSERT OR IGNORE INTO dams (name, name_normalised, breed_code, tih_flag, sire_id) VALUES (${q(d.name)}, ${q(d.name_normalised)}, ${q(d.breed_code)}, ${d.tih_flag}, ${sireId(d.sire)})`);
}
for (const b of rows('SELECT name, name_normalised, county FROM breeders ORDER BY id')) {
  add(`INSERT OR IGNORE INTO breeders (name, name_normalised, county) VALUES (${q(b.name)}, ${q(b.name_normalised)}, ${q(b.county)})`);
}
for (const h of rows(`SELECT h.name, h.sex, h.breed_code, h.tih_flag, h.notes, ${HORSE_KEY}, ds.name_normalised AS damsire, b.name_normalised AS breeder, b.county AS breeder_county
    FROM horses h ${HORSE_JOIN} LEFT JOIN sires ds ON ds.id = h.damsire_id LEFT JOIN breeders b ON b.id = h.breeder_id ORDER BY h.id`)) {
  add(`INSERT OR IGNORE INTO horses (name, name_normalised, birth_year, sex, breed_code, tih_flag, notes, sire_id, dam_id, damsire_id, breeder_id)
    VALUES (${q(h.name)}, ${q(h.h_norm)}, ${h.h_year ?? 'NULL'}, ${q(h.sex)}, ${q(h.breed_code)}, ${h.tih_flag}, ${q(h.notes)},
    ${sireId(h.h_sire)}, ${damId(h.h_dam, h.h_dam_sire)}, ${sireId(h.damsire)}, ${breederId(h.breeder, h.breeder_county)})`);
}
for (const a of rows(`SELECT a.former_name, a.former_name_normalised, ${HORSE_KEY} FROM horse_aliases a JOIN horses h ON h.id = a.horse_id ${HORSE_JOIN} ORDER BY a.id`)) {
  add(`INSERT OR IGNORE INTO horse_aliases (horse_id, former_name, former_name_normalised) VALUES (${horseId(a)}, ${q(a.former_name)}, ${q(a.former_name_normalised)})`);
}

// Events, classes and uploads (batches)
for (const e of rows('SELECT name, date_text, start_date, end_date, country, season, source_notes FROM events ORDER BY id')) {
  add(`INSERT OR IGNORE INTO events (name, date_text, start_date, end_date, country, season, source_notes)
    VALUES (${q(e.name)}, ${q(e.date_text)}, ${q(e.start_date)}, ${q(e.end_date)}, ${q(e.country)}, ${e.season}, ${q(e.source_notes)})`);
}
for (const c of rows(`SELECT c.name AS cl_name, ${EVENT_KEY} FROM classes c JOIN events e ON e.id = c.event_id ORDER BY c.id`)) {
  add(`INSERT OR IGNORE INTO classes (event_id, name) VALUES (${eventId(c)}, ${q(c.cl_name)})`);
}
const batches = rows('SELECT label, created_at FROM batches ORDER BY id');
for (const b of batches) {
  add(`INSERT INTO batches (label, created_at, row_count, unverified_count) SELECT ${q(b.label)}, ${q(b.created_at)}, 0, 0
    WHERE NOT EXISTS (SELECT 1 FROM batches WHERE label = ${q(b.label)})`);
}

// Results (breeding tables) and placings (public results pages)
for (const r of rows(`SELECT r.rider_name, r.rider_country, r.class_name, r.placing, r.dressage, r.xc_jumping, r.show_jumping, r.total, r.week_label, r.verified, r.created_at,
    b.label AS batch, ${EVENT_KEY}, ${HORSE_KEY}
    FROM results r JOIN events e ON e.id = r.event_id JOIN horses h ON h.id = r.horse_id ${HORSE_JOIN} LEFT JOIN batches b ON b.id = r.batch_id ORDER BY r.id`)) {
  add(`INSERT OR IGNORE INTO results (event_id, horse_id, rider_name, rider_country, class_name, placing, dressage, xc_jumping, show_jumping, total, week_label, verified, batch_id, created_at)
    VALUES (${eventId(r)}, ${horseId(r)}, ${q(r.rider_name)}, ${q(r.rider_country)}, ${q(r.class_name)}, ${r.placing ?? 'NULL'}, ${q(r.dressage)}, ${q(r.xc_jumping)},
    ${q(r.show_jumping)}, ${r.total ?? 'NULL'}, ${q(r.week_label)}, ${r.verified}, ${batchId(r.batch)}, ${q(r.created_at)})`);
}
for (const p of rows(`SELECT p.position, p.horse_name, p.former_name, p.breed, p.foaled, p.sex, p.sire, p.dam, p.dam_sire, p.breeder, p.dressage, p.show_jumping,
    p.cross_country, p.score, p.verified, c.name AS cl_name, b.label AS batch, ${EVENT_KEY},
    r.class_name AS r_class, ${HORSE_KEY}
    FROM placings p JOIN classes c ON c.id = p.class_id JOIN events e ON e.id = c.event_id LEFT JOIN batches b ON b.id = p.batch_id
    LEFT JOIN results r ON r.id = p.result_id LEFT JOIN horses h ON h.id = r.horse_id ${HORSE_JOIN} ORDER BY p.id`)) {
  const resultId = p.r_class ? `(SELECT id FROM results WHERE event_id = ${eventId(p)} AND class_name = ${q(p.r_class)} AND horse_id = ${horseId(p)})` : 'NULL';
  add(`INSERT OR IGNORE INTO placings (class_id, batch_id, result_id, position, horse_name, former_name, breed, foaled, sex, sire, dam, dam_sire, breeder,
    dressage, show_jumping, cross_country, score, verified)
    VALUES (${classId(p)}, ${batchId(p.batch)}, ${resultId}, ${p.position ?? 'NULL'}, ${q(p.horse_name)}, ${q(p.former_name)}, ${q(p.breed)}, ${p.foaled ?? 'NULL'},
    ${q(p.sex)}, ${q(p.sire)}, ${q(p.dam)}, ${q(p.dam_sire)}, ${q(p.breeder)}, ${q(p.dressage)}, ${q(p.show_jumping)}, ${q(p.cross_country)}, ${p.score ?? 'NULL'}, ${p.verified})`);
}
for (const b of batches) {
  add(`UPDATE batches SET row_count = (SELECT COUNT(*) FROM placings WHERE batch_id = batches.id),
    unverified_count = (SELECT COUNT(*) FROM placings WHERE batch_id = batches.id AND verified = 0) WHERE label = ${q(b.label)}`);
}

// Spellings Charlie confirmed as the same record, so the next paste doesn't ask again
for (const m of rows(`SELECT m.kind, m.match_key,
    s.name_normalised AS s_norm, d.name_normalised AS d_norm, dsr.name_normalised AS d_sire, b.name_normalised AS b_norm, b.county AS b_county, ${HORSE_KEY}
    FROM name_matches m
    LEFT JOIN sires s ON m.kind = 'sire' AND s.id = m.target_id
    LEFT JOIN dams d ON m.kind = 'dam' AND d.id = m.target_id LEFT JOIN sires dsr ON dsr.id = d.sire_id
    LEFT JOIN breeders b ON m.kind = 'breeder' AND b.id = m.target_id
    LEFT JOIN horses h ON m.kind = 'horse' AND h.id = m.target_id ${HORSE_JOIN} ORDER BY m.id`)) {
  const target = { sire: sireId(m.s_norm), dam: damId(m.d_norm, m.d_sire), breeder: breederId(m.b_norm, m.b_county), horse: horseId(m) }[m.kind];
  add(`INSERT OR IGNORE INTO name_matches (kind, match_key, target_id) SELECT ${q(m.kind)}, ${q(m.match_key)}, ${target} WHERE ${target} IS NOT NULL`);
}

// Articles and link cards
for (const n of rows('SELECT title, body, snippet, source_url, source_name, published_at, sort_order FROM news ORDER BY sort_order, id')) {
  add(`INSERT INTO news (title, body, snippet, source_url, source_name, published_at, sort_order)
    SELECT ${q(n.title)}, ${q(n.body)}, ${q(n.snippet)}, ${q(n.source_url)}, ${q(n.source_name)}, ${q(n.published_at)}, ${n.sort_order}
    WHERE NOT EXISTS (SELECT 1 FROM news WHERE title = ${q(n.title)})`);
  // An article added earlier by "npm run content:remote" keeps its text but takes the agreed date.
  add(`UPDATE news SET published_at = ${q(n.published_at)} WHERE title = ${q(n.title)}`);
}
for (const l of rows('SELECT title, url, teaser, source_name, card_date, sort_order FROM link_cards ORDER BY sort_order, id')) {
  add(`INSERT INTO link_cards (title, url, teaser, source_name, card_date, sort_order)
    SELECT ${q(l.title)}, ${q(l.url)}, ${q(l.teaser)}, ${q(l.source_name)}, ${q(l.card_date)}, ${l.sort_order}
    WHERE NOT EXISTS (SELECT 1 FROM link_cards WHERE title = ${q(l.title)})`);
}

writeFileSync(new URL('../migrations/0005_launch_content.sql', import.meta.url), out.join('\n') + '\n');
console.log(`migrations/0005_launch_content.sql: ${out.length - 5} statements`);

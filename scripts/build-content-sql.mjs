// Turns seed/starter-content.json into seed/starter-content.sql, which adds any article or link card
// whose headline isn't on the site yet (safe to run more than once). Used by:
//   npm run content:local    and    npm run content:remote   (the live site)
import { readFileSync, writeFileSync } from 'node:fs';

const data = JSON.parse(readFileSync(new URL('../seed/starter-content.json', import.meta.url), 'utf8'));
const q = v => `'${String(v ?? '').replace(/'/g, "''")}'`;
const snippet = body => { const flat = body.replace(/\s+/g, ' ').trim(); return flat.length > 220 ? flat.slice(0, 220).replace(/\s+\S*$/, '') + '…' : flat; };
const out = ['-- Generated by scripts/build-content-sql.mjs from seed/starter-content.json. Do not edit by hand.'];

data.news.forEach((n, i) => {
  const when = n.date ? q(`${n.date} 12:00:00`) : "datetime('now')";
  out.push(`INSERT INTO news (title, body, snippet, source_url, source_name, published_at, sort_order)
SELECT ${q(n.title)}, ${q(n.body)}, ${q(snippet(n.body))}, ${q(n.source_url)}, ${q(n.source_name)}, ${when}, ${i + 1}
WHERE NOT EXISTS (SELECT 1 FROM news WHERE title = ${q(n.title)});`);
});
data.links.forEach((l, i) => {
  out.push(`INSERT INTO link_cards (title, url, teaser, source_name, card_date, sort_order)
SELECT ${q(l.title)}, ${q(l.url)}, ${q(l.teaser)}, ${q(l.source_name)}, ${q(l.date)}, ${i + 1}
WHERE NOT EXISTS (SELECT 1 FROM link_cards WHERE title = ${q(l.title)});`);
});
writeFileSync(new URL('../seed/starter-content.sql', import.meta.url), out.join('\n\n') + '\n');
console.log(`seed/starter-content.sql: ${data.news.length} articles, ${data.links.length} link cards`);

// Writes migrations-ibsr/0001_site_tables.sql: IBER's table structure (news, ads, comments, subscribers, settings,
// analytics, stallion listings, results pages…) with none of IBER's content, for the showjumping site's own database.
// It builds IBER's tables from migrations/ in a throwaway in-memory database and copies only the CREATE statements.
//   node scripts/build-ibsr-site-schema.mjs
import { DatabaseSync } from 'node:sqlite';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../migrations/', import.meta.url);
const db = new DatabaseSync(':memory:');
const files = readdirSync(dir).filter(f => f.endsWith('.sql')).sort();
for (const f of files) db.exec(readFileSync(new URL(f, dir), 'utf8'));

const rows = db.prepare(`SELECT type, name, tbl_name, sql FROM sqlite_master
  WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_cf_%' AND name <> 'd1_migrations'
  ORDER BY rowid`).all();
// FTS5 makes its own shadow tables when the virtual table is created.
const fts = rows.filter(r => /CREATE VIRTUAL TABLE/i.test(r.sql)).map(r => r.name);
const keep = rows.filter(r => !fts.some(v => r.name !== v && r.name.startsWith(`${v}_`)));

// Settings rows the code expects to exist (not content).
const settings = db.prepare("SELECT key, value FROM settings WHERE key IN ('ad_price_top', 'ad_price_side')").all();
const q = s => `'${String(s).replace(/'/g, "''")}'`;

const out = [
  '-- IrishBredShowjumpingResults (IBSR) site database: the same tables as IBER (from migrations/0001 to',
  `-- ${files.at(-1)}), empty. None of IBER's results, articles, ads or subscribers are copied.`,
  '-- Generated by scripts/build-ibsr-site-schema.mjs. Edit IBER\'s migrations, then run it again.',
  '',
  ...keep.map(r => `${r.sql.trim()};`),
  '',
  ...settings.map(s => `INSERT OR IGNORE INTO settings (key, value) VALUES (${q(s.key)}, ${q(s.value)});`),
  ''
].join('\n');
writeFileSync(new URL('../migrations-ibsr/0001_site_tables.sql', import.meta.url), out);
console.log(`${keep.length} statements (${keep.filter(r => r.type === 'table').length} tables) → migrations-ibsr/0001_site_tables.sql`);
